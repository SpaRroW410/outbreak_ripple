"""Write docs/QUALITY_REPORT.md from the numbers the tests saved in reports/*.json.

Run by `make check` after all tests. The report contains measurements only;
nothing here is typed by hand.
"""

from __future__ import annotations

import json
import platform
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "reports"
TARGET = ROOT / "docs" / "QUALITY_REPORT.md"
EXPECTED = ("determinism", "stream_isolation", "causality", "causality_brute_force",
            "counterfactual", "conservation", "sanity_epidemic_threshold",
            "sanity_herd_immunity", "butterfly", "balance", "ui", "performance")


def load(name: str) -> dict[str, Any]:
    """One saved report, or {} if the test has not been run."""
    path = REPORTS / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def bullet(label: str, data: dict[str, Any], keys: list[str]) -> list[str]:
    """A heading and one line per key."""
    lines = [f"## {label}", ""]
    if not data:
        return lines + ["Not measured in this run.", ""]
    lines += [f"- {key.replace('_', ' ')}: {json.dumps(data[key])}" for key in keys if key in data]
    return lines + [""]


def render() -> str:
    """The Markdown report."""
    herd = load("sanity_herd_immunity").get("results", [])
    lines = ["# Quality report", "",
             "Generated by `python -m tools.quality_report` (part of `make check`) from",
             "`reports/*.json`. Do not edit by hand. Native test environment: Python "
             f"{platform.python_version()} on {platform.system()} {platform.machine()}.", ""]
    lines += bullet("Determinism", load("determinism"),
                    ["seeds", "runs_per_seed", "mismatched_seeds", "state_mismatches",
                     "distinct_logs", "mean_events_per_run"])
    lines += bullet("Stream isolation", load("stream_isolation"),
                    ["seeds", "configurations_per_seed", "stream_checks", "failures"])
    lines += bullet("Causality", load("causality"),
                    ["seeds", "events", "missing_cause", "cause_not_earlier",
                     "cause_from_the_future"])
    lines += bullet("Causality: longest chain against brute force", load("causality_brute_force"),
                    ["small_worlds", "chains_checked", "longest_chain_seen", "mismatches"])
    lines += bullet("Counterfactual", load("counterfactual"),
                    ["seeds", "empty_diff_nonzero", "runs_with_any_difference",
                     "player_only_events", "player_only_events_not_downstream",
                     "differences_before_action", "changed_state_cells",
                     "changed_state_cells_without_taint"])
    lines += bullet("Conservation", load("conservation"),
                    ["seeds", "ticks_checked", "violations", "doses_given"])
    lines += bullet("Model sanity: epidemic threshold", load("sanity_epidemic_threshold"),
                    ["expected", "measured_threshold_r0", "r0_grid", "mean_attack_rate"])
    lines += ["## Model sanity: herd immunity threshold", ""]
    lines += [f"- R0 {row['r0']}: expected {row['expected']}, measured "
              f"{row['measured_threshold']}" for row in herd] or ["Not measured in this run."]
    lines += [""]
    lines += bullet("Butterfly (ripple size of one random card, per seed)", load("butterfly"),
                    ["seeds", "quantiles", "max", "mean", "share_zero", "large_means_at_least",
                     "share_large", "top_1_percent_share_of_total", "large_share_by_card"])
    lines += bullet("Balance (random-policy runs)", load("balance"),
                    ["runs", "top_runs", "limit", "max_card_share_in_top", "card_share_in_top",
                     "family_share_in_top", "family_share_in_all", "score_quantiles"])
    lines += bullet("UI smoke test", load("ui"),
                    ["viewport", "turns_played", "screens_scanned", "axe_violations",
                     "overflow_at_200", "external_requests", "console_errors", "failures"])
    lines += bullet("Performance (Pyodide build)", load("performance"),
                    ["what", "median_ms", "min_ms", "max_ms", "budget_ms", "engine_ready_ms",
                     "results_screen_ms", "environment", "same_log_as_native_python"])
    return "\n".join(lines)


def main() -> int:
    """Write the report; exit 1 if a measurement is missing."""
    TARGET.write_text(render(), encoding="utf-8")
    missing = [name for name in EXPECTED if not load(name)]
    print(f"wrote {TARGET}" + (f" (missing: {', '.join(missing)})" if missing else ""))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
