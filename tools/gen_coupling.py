"""Generate docs/COUPLING.md from the domains' declared reads and writes.

Run `python -m tools.gen_coupling` after changing any domain's keys.
`--check` exits 1 if the file on disk is out of date (used by `make check`).
"""

from __future__ import annotations

import sys
from pathlib import Path

from engine.registry import build_domains

TARGET = Path(__file__).resolve().parent.parent / "docs" / "COUPLING.md"


def render() -> str:
    """The Markdown text of the coupling document."""
    domains = build_domains()
    owner = {key: domain.name for domain in domains for key in domain.writes}
    lines = ["# Cross-domain coupling", "",
             "Generated by `python -m tools.gen_coupling` from each domain's declared",
             "`reads` and `writes`. Do not edit by hand.", "",
             "Domains step in this order each tick: "
             + ", ".join(f"`{domain.name}`" for domain in domains) + ".", "",
             "## Keys read across domains", "",
             "| Reader | Key | Owner (writer) |", "|---|---|---|"]
    for domain in domains:
        for key in sorted(domain.reads):
            lines.append(f"| {domain.name} | `{key}` | {owner.get(key, 'nobody (missing!)')} |")
    lines += ["", "Player action cards may write any existing key (see `content/cards/`)."]
    for domain in domains:
        lines += ["", f"## Keys owned by `{domain.name}`", ""]
        lines += [f"- `{key}`" for key in sorted(domain.writes)]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the file, or check it with --check."""
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("docs/COUPLING.md is out of date: run python -m tools.gen_coupling")
            return 1
        print("coupling doc OK")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
